-- Preserve existing custom statuses, inserting only missing names in each scope.
FOR scope_key IN SELECT _scope FROM scopes LOOP
    SELECT array_agg(name ORDER BY sort_order,name) INTO status_order
        FROM task_statuses WHERE _scope=scope_key;
    status_order := COALESCE(status_order, ARRAY[]::text[]);
    added := false;
    FOR entry IN SELECT * FROM (VALUES
        ('backlog','Backlog','#94a3b8','Not ready for work yet. No built-in job picks it up.',0,0),
        ('plan_review','Plan in review','#8b5cf6','A plan for this task waits for a human decision.',1,1)
    ) AS v(name,label,color,description,is_system,anchor_offset) LOOP
        IF entry.name = ANY(status_order) THEN CONTINUE; END IF;
        INSERT INTO task_statuses (_scope,name,label,color,description,is_system,sort_order)
            VALUES (scope_key,entry.name,entry.label,entry.color,entry.description,entry.is_system,0);
        anchor := COALESCE(array_position(status_order,'pending') + entry.anchor_offset,
                           cardinality(status_order)+1);
        status_order := status_order[:anchor-1] || ARRAY[entry.name] || status_order[anchor:];
        added := true;
    END LOOP;
    IF added THEN
        UPDATE task_statuses SET sort_order = s.position-1
            FROM unnest(status_order) WITH ORDINALITY AS s(name,position)
            WHERE _scope=scope_key AND task_statuses.name=s.name;
    END IF;
END LOOP;

CREATE OR REPLACE FUNCTION protect_actor() RETURNS trigger LANGUAGE plpgsql AS $actor$
BEGIN
    IF TG_TABLE_NAME = 'accounts' THEN
        IF NOT EXISTS (SELECT 1 FROM actor_refs WHERE _scope=NEW._scope AND id=NEW.actor_id AND kind='human') THEN
            RAISE EXCEPTION 'accounts.actor_id must reference a human actor_ref' USING ERRCODE='23514';
        END IF;
        RETURN NEW;
    END IF;
    IF TG_OP='DELETE' THEN
        RAISE EXCEPTION 'actor identities cannot be deleted' USING ERRCODE='23514';
    END IF;
    IF TG_OP='INSERT' THEN
        IF NEW.kind!='system' AND EXISTS (SELECT 1 FROM actor_refs WHERE _scope=NEW._scope AND id=NEW.id AND kind='system') THEN
            RAISE EXCEPTION 'system actor cannot be replaced' USING ERRCODE='23514';
        END IF;
        RETURN NEW;
    END IF;
    IF OLD.kind='system' AND (NEW.kind IS DISTINCT FROM OLD.kind OR NEW._scope IS DISTINCT FROM OLD._scope OR
        (NEW.id IS DISTINCT FROM OLD.id AND NOT EXISTS (
            SELECT 1 FROM instance_secrets WHERE _scope=OLD._scope AND name='system_principal_id' AND value=NEW.id
        ))) THEN
        RAISE EXCEPTION 'system actor identity is immutable' USING ERRCODE='23514';
    END IF;
    IF NEW.kind!='human' AND EXISTS (SELECT 1 FROM accounts WHERE _scope=OLD._scope AND actor_id=OLD.id) THEN
        RAISE EXCEPTION 'referenced actor must stay human' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$actor$;
CREATE TRIGGER actor_insert BEFORE INSERT ON actor_refs FOR EACH ROW EXECUTE FUNCTION protect_actor();

